"""Write private-app/map-summary.js: the small slice of the title-trace and road-wording data the map needs at start-up.

The map colours parcels, counts them, fills the side-panel summaries and searches earlier-deed references as soon as it
loads. Those need only the statistics, each parcel's approved classification and its earlier-deed reference numbers.
The full evidence (title-trace.js, 375 KB; road-wording.js, 800 KB) is fetched the first time a parcel popup opens.

Run after regenerating title-trace.js or road-wording.js:  python tools/split-map-data.py
(tools/tests/test_map_summary.py fails while the summary is out of date.)
"""

import json
import re
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent / "private-app"
OUT = APP / "map-summary.js"


def read_consts(path: Path) -> dict:
    """Each data script is one `const NAME = <json>;` per line."""
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"const (\w+) = (.*);\s*$", line)
        if m:
            values[m.group(1)] = json.loads(m.group(2))
    return values


def build() -> str:
    trace = read_consts(APP / "title-trace.js")
    road = read_consts(APP / "road-wording.js")
    parcels = {}
    for index, t in trace["TITLE_TRACE"].items():
        entry = {}
        if t.get("approved_classification"):
            entry["approved_classification"] = t["approved_classification"]
        refs = [i["ref"] for i in t.get("earlier_instruments") or [] if i.get("ref")]
        if refs:
            entry["refs"] = refs
        parcels[index] = entry
    summary = {"title_stats": trace["TITLE_TRACE_STATS"], "road_stats": road["ROAD_STATS"], "trace": parcels}
    return ("// Generated by tools/split-map-data.py from title-trace.js and road-wording.js. Do not edit by hand.\n"
            "window.HBA_MAP_SUMMARY = " + json.dumps(summary, ensure_ascii=False, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name}: {len(text.encode()):,} bytes")
